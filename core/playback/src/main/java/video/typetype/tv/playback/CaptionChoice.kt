package video.typetype.tv.playback

import video.typetype.tv.data.SubtitleTrack

object CaptionChoice {
    private const val MAX_LANGUAGES = 8

    fun languages(tracks: List<SubtitleTrack>): List<SubtitleTrack> =
        tracks.sortedBy { it.autoGenerated }.distinctBy { it.language }.take(MAX_LANGUAGES)

    fun matches(tag: String, preferred: String): Boolean =
        preferred.isNotBlank() && tag.substringBefore('-').equals(preferred.substringBefore('-'), ignoreCase = true)
}
