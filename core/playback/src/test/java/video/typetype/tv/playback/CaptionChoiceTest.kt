package video.typetype.tv.playback

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import video.typetype.tv.data.SubtitleTrack

class CaptionChoiceTest {
    private fun track(language: String, auto: Boolean = false) =
        SubtitleTrack("https://s.example/$language", "application/ttml+xml", language, language, auto)

    @Test
    fun manualTracksWinOverGeneratedOnesOfTheSameLanguage() {
        val chosen = CaptionChoice.languages(listOf(track("en", auto = true), track("en"), track("de-DE")))
        assertEquals(listOf("en", "de-DE"), chosen.map { it.language })
        assertFalse(chosen.first { it.language == "en" }.autoGenerated)
    }

    @Test
    fun theLanguageListIsBounded() {
        val many = (1..20).map { track("l$it") }
        assertEquals(8, CaptionChoice.languages(many).size)
    }

    @Test
    fun preferredLanguageMatchesRegionalVariants() {
        assertTrue(CaptionChoice.matches("pt-BR", "pt"))
        assertTrue(CaptionChoice.matches("en", "EN"))
        assertFalse(CaptionChoice.matches("de-DE", "fr"))
        assertFalse(CaptionChoice.matches("en", ""))
    }
}
