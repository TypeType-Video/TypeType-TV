package video.typetype.tv.data

import video.typetype.tv.data.dto.StreamDto

data class SubtitleTrack(
    val url: String,
    val mimeType: String,
    val language: String,
    val label: String,
    val autoGenerated: Boolean,
)

data class SponsorSegment(
    val startMs: Long,
    val endMs: Long,
    val category: String,
    val action: String,
    val autoSkip: Boolean = false,
)

data class PlaybackPreferences(
    val maxHeight: Int? = null,
    val speed: Float = 1f,
    val captionsOn: Boolean = false,
    val captionLanguage: String = "",
    val autoplay: Boolean = true,
    val autoplayCountdownSeconds: Int = DEFAULT_COUNTDOWN_SECONDS,
    val skipSponsors: Boolean = false,
    val muteSponsors: Boolean = false,
    val showCurrentSegment: Boolean = true,
    val captionStyles: CaptionStyles = CaptionStyles(),
    val hideComments: Boolean = false,
    val audioLanguage: String = "",
    val preferOriginalAudio: Boolean = false,
) {
    companion object {
        const val DEFAULT_COUNTDOWN_SECONDS = 10
    }
}

data class PlaybackSetup(
    val preferences: PlaybackPreferences = PlaybackPreferences(),
    val subtitles: List<SubtitleTrack> = emptyList(),
    val sponsorSegments: List<SponsorSegment> = emptyList(),
    val liveManifest: String? = null,
    val storyboard: Storyboard? = null,
    val stream: StreamDto? = null,
)
