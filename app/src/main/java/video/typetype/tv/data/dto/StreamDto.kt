package video.typetype.tv.data.dto

import kotlinx.serialization.Serializable

@Serializable
data class StreamDto(
    val id: String = "",
    val title: String = "",
    val uploaderName: String = "",
    val uploaderUrl: String = "",
    val uploaderAvatarUrl: String? = null,
    val thumbnailUrl: String? = null,
    val description: String = "",
    val duration: Long = 0,
    val viewCount: Long = -1,
    val likeCount: Long = -1,
    val uploaded: Long = -1,
    val uploaderSubscriberCount: Long = -1,
    val category: String = "",
    val tags: List<String> = emptyList(),
    val streamType: String = "video_stream",
    val isLive: Boolean = false,
    val hlsUrl: String = "",
    val streamSegments: List<StreamSegmentDto> = emptyList(),
    val videoOnlyStreams: List<VideoStreamDto> = emptyList(),
    val audioStreams: List<AudioStreamDto> = emptyList(),
    val subtitles: List<SubtitleDto> = emptyList(),
    val sponsorBlockSegments: List<SponsorBlockSegmentDto> = emptyList(),
    val relatedStreams: List<VideoItemDto> = emptyList(),
    val previewFrames: List<PreviewFrameDto> = emptyList(),
)

@Serializable
data class PreviewFrameDto(
    val urls: List<String> = emptyList(),
    val frameWidth: Int = 0,
    val frameHeight: Int = 0,
    val totalCount: Int = 0,
    val durationPerFrame: Long = 0,
    val framesPerPageX: Int = 0,
    val framesPerPageY: Int = 0,
)

@Serializable
data class VideoStreamDto(
    val itag: Int = 0,
    val codec: String = "",
    val mimeType: String = "",
    val width: Int = 0,
    val height: Int = 0,
    val fps: Int = 0,
    val bitrate: Int = 0,
    val deliveryMethod: String = "",
    val url: String = "",
    val resolution: String = "",
)

@Serializable
data class AudioStreamDto(
    val itag: Int = 0,
    val codec: String = "",
    val mimeType: String = "",
    val bitrate: Int = 0,
    val audioTrackId: String? = null,
    val audioTrackName: String? = null,
    val audioLocale: String? = null,
    val isOriginal: Boolean = false,
    val deliveryMethod: String = "",
    val url: String = "",
    val quality: String = "",
)

@Serializable
data class SubtitleDto(
    val url: String = "",
    val mimeType: String = "",
    val languageTag: String = "",
    val displayLanguageName: String = "",
    val isAutoGenerated: Boolean = false,
)

@Serializable
data class StreamSegmentDto(
    val title: String = "",
    val startTimeSeconds: Int = 0,
    val previewUrl: String? = null,
)

@Serializable
data class SponsorBlockSegmentDto(
    val startTime: Double = 0.0,
    val endTime: Double = 0.0,
    val category: String = "",
    val action: String = "",
)
